function build(category: OpenHeartCategory, prefix: string, texts: string[]): OpenHeartQuestion[] {
  return texts.map((text, i) => ({ id: `${prefix}-${String(i + 1).padStart(3, '0')}`, category, text }))
}

export const OPEN_HEART_QUESTIONS: OpenHeartQuestion[] = [
  ...build('today', 'ohq-today', today),
  ...build('feelings', 'ohq-feelings', feelings),
  ...build('family', 'ohq-family', family),
  ...build('friends', 'ohq-friends', friends),
  ...build('dreams', 'ohq-dreams', dreams),
  ...build('gratitude', 'ohq-gratitude', gratitude),
  ...build('understanding', 'ohq-understanding', understanding),
]

export function getOpenHeartQuestionById(id: string): OpenHeartQuestion | undefined {
  return OPEN_HEART_QUESTIONS.find((q) => q.id === id)
}
